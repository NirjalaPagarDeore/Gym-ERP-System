function editCategory(id, fileName) {

    // Create invisible form
    var form = document.createElement("form");
    form.method = "POST";
    form.action = fileName;

    // Create hidden input
    var input = document.createElement("input");
    input.type = "hidden";
    input.name = "id";
    input.value = id;

    form.appendChild(input);
    document.body.appendChild(form);

    // Submit form (POST)
    form.submit();
}
</script>



